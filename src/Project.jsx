const Project = ({ darkMode = true }) => {
  const palette = getPalette(darkMode);
  const reduced = usePrefersReducedMotion();
  const [details, setDetails] = useState(null);
  const { launch, start, setStage, close } = useWarpLaunch(reduced);
  const [headerRef, headerIn] = useInViewOnce(0.2);
  const headerShown = headerIn || reduced;

  const liveCount = websites.filter((s) => hostOf(s.url)).length;
  const [flashed, setFlashed] = useState(null);
  const flashTimer = useRef(0);
  useEffect(() => () => clearTimeout(flashTimer.current), []);
  const jumpTo = (site) => {
    document.getElementById(`project-${slugOf(site.name)}`)?.scrollIntoView({ behavior: reduced ? 'auto' : 'smooth', block: 'center' });
    clearTimeout(flashTimer.current);
    setFlashed(null);
    requestAnimationFrame(() => setFlashed(site.name));
    flashTimer.current = setTimeout(() => setFlashed(null), 2600);
  };

  const closeDetails = useCallback(() => setDetails(null), []);
  const launchFromDetails = (site, e) => {
    setDetails(null);
    start(site, e);
  };

  const warping = launch && (launch.stage === 'boot' || launch.stage === 'jump');
  const headerStep = (n) => ({
    opacity: headerShown ? 1 : 0,
    transform: headerShown ? 'none' : 'translateY(24px)',
    transition: 'opacity 700ms ease, transform 700ms cubic-bezier(0.22,1,0.36,1)',
    transitionDelay: reduced ? '0ms' : `${n * 100}ms`,
  });

  return (
    <div className="pj-scope relative" style={cssVars(palette)}>
      <ProjectStyles />

      {details && <ProjectDetails site={details} darkMode={darkMode} onClose={closeDetails} onLaunch={launchFromDetails} />}
      {launch && (
        <WarpLaunch
          key={launch.id}
          launch={launch}
          palette={palette}
          darkMode={darkMode}
          setStage={setStage}
          close={close}
        />
      )}

      <div
        style={{
          transform: warping ? 'scale(0.94)' : 'none',
          filter: warping ? 'blur(4px)' : 'none',
          transition: 'transform 800ms cubic-bezier(0.16,1,0.3,1), filter 800ms ease',
        }}
        className="space-y-16 sm:space-y-24 text-[color:var(--ink)]"
      >
        {/* ================= HEADER ================= */}
        {/* intro on the left, the app dock beside it on wide screens */}
        <header ref={headerRef} className="relative grid lg:grid-cols-[1fr_auto] gap-8 lg:gap-12 items-center pt-4">
          <HandStyles />
          <div className="space-y-5 sm:space-y-6">
          <p style={headerStep(0)} className="pj-acc font-mono text-[0.6875rem] uppercase tracking-[0.25em]">
            ~/projects
          </p>
          <h2 style={headerStep(1)} className="text-4xl sm:text-6xl md:text-7xl font-black tracking-tighter leading-[0.95]">
            Things I&apos;ve{' '}
            <span className="relative inline-block">
              <span className="pj-acc">shipped.</span>
              <Doodle type="underline" className="absolute left-0 -bottom-2 w-full h-3 sm:h-4" strokeWidth={4} delay={0.6} />
            </span>
          </h2>
          <HandNote className="text-2xl sm:text-3xl" rot={-2} delay={0.8}>
            (all live — go click &apos;em!)
          </HandNote>
          <p style={headerStep(2)} className="text-sm sm:text-lg opacity-70 max-w-2xl leading-relaxed">
            Live, deployed apps — from an AI productivity coach and an AI screenshot sorter to a community map and a
            retro chess game. Tap an app to jump to it.
          </p>
          <div style={headerStep(3)} className="flex flex-wrap gap-3">
            {[
              `${String(liveCount).padStart(2, '0')} live apps`,
              `${String(websites.length).padStart(2, '0')} apps built`,
              'Deployed on Vercel',
            ].map((label) => (
              <span
                key={label}
                className="px-3 py-1.5 rounded-md border border-[color:var(--acc-line)] bg-[color:var(--acc-soft)] text-[0.625rem] sm:text-[0.6875rem] font-black uppercase tracking-[0.2em] pj-acc"
              >
                {label}
              </span>
            ))}
          </div>
          </div>
          <div style={headerStep(4)} className="pt-2 sm:pt-4 lg:pt-0">
            <AppDock sites={websites} reduced={reduced} shown={headerShown} onPick={jumpTo} />
          </div>
        </header>

        {/* ================= WEBSITES ================= */}
        <section>
          <SectionEyebrow label="Websites & Apps" icon={<Globe size={16} />} />
          <p className="text-sm sm:text-base opacity-65 max-w-2xl mb-8 sm:mb-10">
            Tap <span className="pj-acc font-black">View details</span> for screenshots and the full story, or hit{' '}
            <span className="pj-acc font-black">Launch Site</span> to warp straight into the live app.
          </p>
          <div className="space-y-12 sm:space-y-16">
            {websites.map((site, idx) => (
              <ProjectRow
                key={site.name}
                site={site}
                index={idx}
                reduced={reduced}
                onDetails={setDetails}
                onLaunch={start}
                flash={flashed === site.name}
              />
            ))}
          </div>
        </section>

      </div>
    </div>
  );
};

